--From the table CUSTOMER perform the following queries:  

--Part – A: 

--1. Display top 3 highest amount orders. 
WITH TOP3_AMT AS (
	SELECT *,
	ROW_NUMBER() OVER (ORDER BY AMOUNT DESC) AS [SR.NO.]
	FROM CUSTOMER_ALL
)
SELECT TOP 3 * FROM TOP3_AMT

--2. Display second highest order amount. 
WITH SECOND_HIGHEST AS (
	SELECT ROW_NUMBER() OVER (ORDER BY AMOUNT DESC) AS [SR.NO.],*
	FROM CUSTOMER_ALL
)
SELECT * FROM SECOND_HIGHEST
WHERE [SR.NO.] = 2

--3. Display customers whose order amount is greater than category average amount. 
WITH CATEGORY_WISE_AVG_AMT AS (
	SELECT *, AVG(AMOUNT) OVER (PARTITION BY CATEGORY) AS AVG_AMT 
	FROM CUSTOMER_ALL
)
SELECT * FROM CATEGORY_WISE_AVG_AMT
WHERE AVG_AMT < AMOUNT 

--4. Display categories having average amount greater than 30000. 
WITH CATEGORY_WISE_AVG_AMT AS (
	SELECT CATEGORY, AVG(AMOUNT) AS AVG_AMT 
	FROM CUSTOMER_ALL
	GROUP BY CATEGORY
)
SELECT CATEGORY, AVG_AMT
FROM CATEGORY_WISE_AVG_AMT
WHERE AVG_AMT > 30000

--5. Display highest amount order from each category. 
WITH CATEGORY_WISE_HIGHEST_AMT AS (
	SELECT *,
	ROW_NUMBER() OVER (PARTITION BY CATEGORY ORDER BY AMOUNT DESC) AS RWN_AMT 
	FROM CUSTOMER_ALL
)
SELECT CATEGORY, AMOUNT
FROM CATEGORY_WISE_HIGHEST_AMT
WHERE RWN_AMT = 1

--6. Display lowest amount order from each category. 
WITH CATEGORY_WISE_LOWEST_AMT AS (
	SELECT *,
	ROW_NUMBER() OVER (PARTITION BY CATEGORY ORDER BY AMOUNT) AS RWN_AMT 
	FROM CUSTOMER_ALL
)
SELECT CATEGORY, AMOUNT
FROM CATEGORY_WISE_LOWEST_AMT
WHERE RWN_AMT = 1

--7. Display categories having more than 3 orders. 
WITH CATEGORY_WISE_TOP3_ORDER AS (
	SELECT *,
	ROW_NUMBER() OVER (PARTITION BY CATEGORY ORDER BY AMOUNT) AS RWN_AMT 
	FROM CUSTOMER_ALL
)
SELECT CATEGORY
FROM CATEGORY_WISE_TOP3_ORDER
WHERE RWN_AMT > 3

--8. Display city-wise total order amount. 
WITH CITY_WISE_TOTAL_AMT AS (
	SELECT CITY, SUM(AMOUNT) AS TOTAL_AMT 
	FROM CUSTOMER_ALL
	GROUP BY CITY
)
SELECT CITY, TOTAL_AMT
FROM CITY_WISE_TOTAL_AMT

