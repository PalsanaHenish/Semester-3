--13. Display previous, current and next order amount together. 
WITH PRE_CUR_NEXT_AMT AS (
	SELECT *,
	LAG(AMOUNT) OVER (ORDER BY AMOUNT) AS PRE_AMT,
	AMOUNT AS CUR_AMT,
	LEAD(AMOUNT) OVER (ORDER BY AMOUNT) AS NEXT_AMT
	FROM CUSTOMER_ALL
)
SELECT * FROM PRE_CUR_NEXT_AMT

--14. Display customers whose amount is greater than previous customer's amount. 
WITH PRE_GRE_CUR_AMT AS (
	SELECT *,
	LAG(AMOUNT) OVER (ORDER BY AMOUNT DESC) AS PRE_AMT
	FROM CUSTOMER_ALL
)
SELECT * FROM PRE_GRE_CUR_AMT
WHERE PRE_AMT > AMOUNT

--15. Display customers whose rank and dense rank are different. 
WITH DIFF_RK_DRK AS (
	SELECT *,
	RANK() OVER (ORDER BY AMOUNT DESC) AS RK,
	DENSE_RANK() OVER (ORDER BY AMOUNT DESC) AS DRK
	FROM CUSTOMER_ALL
)
SELECT * FROM DIFF_RK_DRK
WHERE RK != DRK

 
--Part – C: 

--16. Display orders whose amount is neither highest nor lowest in their category. 
WITH AMT_HIGH_LOW AS (
	SELECT *,
	MAX(AMOUNT) OVER (PARTITION BY CATEGORY) AS MAX_AMT,
	MIN(AMOUNT) OVER (PARTITION BY CATEGORY) AS MIN_AMT
	FROM CUSTOMER_ALL
),
AMT_NHIGH_NLOW AS (
	SELECT ORDERID, CNAME, PRODUCT, CATEGORY, AMOUNT, ORDERYEAR, CITY
	FROM AMT_HIGH_LOW
	WHERE AMOUNT > MIN_AMT AND AMOUNT < MAX_AMT
)
SELECT * FROM AMT_NHIGH_NLOW

--17. Display category-wise difference between highest and lowest amount. 
WITH CAT_WISE_DIFF_HIGH_LOW AS (
	SELECT CATEGORY, (MAX(AMOUNT) - MIN(AMOUNT)) AS DIFF_MAX_MIN_AMT
	FROM CUSTOMER_ALL
	GROUP BY CATEGORY
)
SELECT * FROM CAT_WISE_DIFF_HIGH_LOW

--18. Display customers whose amount is greater than all FURNITURE category orders. 
WITH FUR_MAX_AMT AS (
 SELECT MAX(AMOUNT) AS MAX_AMT
 FROM CUSTOMER_ALL
 WHERE CATEGORY = 'FURNITURE'
),
AMT_GREATER_FUR_MAX_AMT AS (
	SELECT * FROM CUSTOMER_ALL
	CROSS JOIN FUR_MAX_AMT
	WHERE AMOUNT > MAX_AMT
)
SELECT * FROM AMT_GREATER_FUR_MAX_AMT

--19. Display categories where all orders are above 10000. 
WITH CAT_HAVE_AMT_ABOVE_10000 AS (
	SELECT CATEGORY
	FROM CUSTOMER_ALL
	GROUP BY CATEGORY
	HAVING MIN(AMOUNT) > 10000
)
SELECT * FROM CAT_HAVE_AMT_ABOVE_10000

--20. Display customers whose amount difference from category topper is minimum. 
